"""V4: compare HeatBank's PHS chain with MEASURED rectal temperature from a dataset you have the right to use.

    python scripts/v4_compare.py --csv data/external/trials_long.csv --out out/v4
    python scripts/v4_compare.py --selftest          # plumbing check on trials generated by PHS itself (proves nothing about physiology)

Input is ONE long CSV that YOU prepare from the dataset's sheets (the dataset's own column names differ, so no loader can be guessed):
    trial_id, minute, tdb_c, tr_c, v_ms, rh_pct, met_wm2, clo, measured_t_re_c            required
    posture (1 sitting, 2 standing, 3 crouching), acclimatized (0 or 100), drink (0 or 1)   optional (defaults 2, 0, 1)
One row per measurement time. Conditions on a row apply to the interval ENDING at that minute. The first row of a trial is the baseline (its conditions
are ignored). met_wm2 is W/m2 (58.15 W/m2 = 1 met); if the dataset gives watts, divide by body surface area first and say so in DATA_SOURCES.md.

Trials whose inputs fall outside HeatBank's validity gate (for example clo above 1.0) are LISTED AS GATED and not compared: in the product they would
be Red, which is the designed behaviour, but it is not an accuracy result. Reports raw error (pred - meas) and 'rise' error (pred rise from the model start
minus measured rise from the first reading), because PHS starts at its default resting temperature, not at the person's baseline.
Declare the dataset in DATA_SOURCES.md before use. Not validation of alerts: it checks the model, one input at a time, against measured people."""
import argparse, csv, math, os, statistics, sys
from collections import defaultdict
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from heatbank.strain.phs_wrapper import StrainEngine, PhsState
from heatbank import config


def load(path):
    trials = defaultdict(list)
    with open(path, newline="") as fh:
        for r in csv.DictReader(fh):
            g = lambda k, d=None: float(r[k]) if r.get(k) not in (None, "") else d
            trials[r["trial_id"]].append(dict(minute=g("minute"), tdb=g("tdb_c"), tr=g("tr_c"), v=g("v_ms"), rh=g("rh_pct"), met=g("met_wm2"), clo=g("clo"),
                                              meas=g("measured_t_re_c"), posture=int(g("posture", 2)), acc=int(g("acclimatized", 0)), drink=int(g("drink", 1))))
    for t in trials.values(): t.sort(key=lambda x: x["minute"])
    return trials


def run_trial(engine, rows):
    """Returns (list of (minute, pred_t_re, meas_t_re), gated_reason or None)."""
    state, out, pred0 = PhsState(), [], None
    for prev, cur in zip(rows, rows[1:]):
        dur = cur["minute"] - prev["minute"]
        if dur <= 0: return [], f"non-increasing minutes at {cur['minute']}"
        r = engine.run_segment(cur["tdb"], cur["tr"], cur["v"], cur["rh"], cur["met"], cur["clo"], cur["posture"], cur["acc"], cur["drink"],
                               duration_min=dur, state=state)
        if r.status not in ("OK", "OK_CLAMPED") or r.t_re_end is None:
            return [], f"{r.status}: {'; '.join(r.reasons) or r.limiting}"
        state = r.state
        out.append((cur["minute"], r.t_re_end, cur["meas"]))
    return out, None


def compare(trials, engine=None):
    engine = engine or StrainEngine()
    res, gated = {}, {}
    for tid, rows in trials.items():
        pts, why = run_trial(engine, rows)
        if why: gated[tid] = why; continue
        meas0 = rows[0]["meas"]
        pred_start = 36.8                                   # PHS default start (2023 mode); stated, not fitted
        res[tid] = dict(
            n=len(pts), raw=[p - m for _, p, m in pts if m is not None],
            rise=[(p - pred_start) - (m - meas0) for _, p, m in pts if m is not None and meas0 is not None])
    return res, gated


def summarize(res, gated, n_total):
    def stats(xs):
        return dict(n=len(xs), bias=round(statistics.mean(xs), 3), mae=round(statistics.mean(abs(x) for x in xs), 3),
                    rmse=round(math.sqrt(statistics.mean(x * x for x in xs)), 3)) if xs else dict(n=0)
    raw = [x for r in res.values() for x in r["raw"]]; rise = [x for r in res.values() for x in r["rise"]]
    return dict(trials_total=n_total, trials_compared=len(res), trials_gated=len(gated), raw=stats(raw), rise=stats(rise))


def report(trials, out):
    res, gated = compare(trials)
    s = summarize(res, gated, len(trials))
    L = ["# V4 comparison: PHS vs measured rectal temperature", "", f"- trials: {s['trials_total']}, compared: {s['trials_compared']}, gated (outside validity range): {s['trials_gated']}",
         f"- raw error (pred - measured, C): {s['raw']}", f"- rise error (C): {s['rise']}", "",
         "Positive bias = the model predicts hotter than measured (the safe direction for alerts). Negative = the model under-predicts: look at those trials first.", "", "## Gated trials", ""]
    L += [f"- {t}: {w}" for t, w in sorted(gated.items())] or ["- none"]
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "v4_summary.md"), "w", encoding="utf-8") as fh: fh.write("\n".join(L))
    print("\n".join(L)); return s


def selftest():
    """Trials generated BY PHS (so the answer is known): bias and error must be about zero, a gated trial must be listed."""
    import random
    e = StrainEngine(); trials = {}
    for k, (tdb, met) in enumerate([(32, 150.0), (36, 200.0)]):
        rows, state, m = [dict(minute=0, tdb=tdb, tr=tdb + 5, v=1.0, rh=50.0, met=met, clo=0.5, meas=36.8, posture=2, acc=0, drink=1)], PhsState(), 0
        for i in range(6):
            r = e.run_segment(tdb, tdb + 5, 1.0, 50.0, met, 0.5, 2, 0, 1, duration_min=10, state=state); state = r.state; m += 10
            rows.append(dict(minute=m, tdb=tdb, tr=tdb + 5, v=1.0, rh=50.0, met=met, clo=0.5, meas=r.t_re_end, posture=2, acc=0, drink=1))
        trials[f"T{k}"] = rows
    trials["GATED"] = [dict(r, clo=2.0) for r in trials["T0"]]
    res, gated = compare(trials, e); s = summarize(res, gated, len(trials))
    assert s["trials_compared"] == 2 and s["trials_gated"] == 1, s
    assert abs(s["raw"]["bias"]) < 0.01 and s["raw"]["mae"] < 0.01, s
    print("selftest OK:", s); return s


def main(argv=None):
    ap = argparse.ArgumentParser(); ap.add_argument("--csv"); ap.add_argument("--out", default="out/v4"); ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest: selftest()
    elif a.csv: report(load(a.csv), a.out)
    else: ap.error("give --csv or --selftest")


if __name__ == "__main__":
    main()
