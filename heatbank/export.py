"""Export a 'pack' for the static phone and supervisor views (plan T5). The model runs HERE (Python, where PHS lives), the
front end only displays. The pack holds archetype-level plan tables, never people. Every pack carries its own provenance
(P4) and a generated_at timestamp so the front end can apply the stale-forecast rule by itself while offline (P2, P5).

Run:  python -m heatbank.export --scenario hot_humid --toy --out dashboard/data.js"""
import argparse, datetime, json, os, sys
from . import config, __version__
from .archetypes.archetypes import build_archetypes
from .dashboard_model import aggregate
from .fallback import fallback
from .i18n import strings
from .provenance import DISCLAIMER
from .sim.harness import simulate_worker, shift_hours
from .sim.toy_model import toy_phs, TOY_LABEL
from .strain.phs_wrapper import StrainEngine
from .weather.scenarios import SyntheticScenario, SCENARIOS

# SYNTHETIC demo roster: crew groups, no names. Zone D is deliberately small (3) to show pooling.
DEMO_ZONES = {"A": "Zone A: foundations", "B": "Zone B: steel frame", "C": "Zone C: loading yard", "D": "Zone D: survey team"}
DEMO_ROSTER = {
    "A": {"A09": 4, "A10": 3, "A05": 2},     # heavy / moderate mix
    "B": {"A07": 3, "A11": 2, "A03": 2, "A04": 1},
    "C": {"A01": 2, "A02": 2, "A05": 3, "A06": 2},
    "D": {"A01": 2, "A02": 1},               # 3 people: below k, gets pooled
}
LEVEL_LABELS = ["Green", "Yellow", "Orange", "Red"]


def _clean_tel(x):
    """Digits and one leading + only, so nothing but a phone number can ever reach a tel: or sms: link."""
    import re
    if not x: return None
    t = re.sub(r"[^0-9+]", "", str(x)); t = ("+" if t.startswith("+") else "") + t.replace("+", "")
    return t if len(t) >= 3 else None


def build_pack(engine, hours, archetypes, roster=None, zone_names=None, model_label="", provider="", synthetic=True,
               forecast_age_min=0.0, now=None, k=None, weather_real=False, attribution=None) -> dict:
    now = now or datetime.datetime.now(datetime.timezone.utc)
    sh = shift_hours(hours)
    per_arch = {}
    for a in archetypes:
        r = simulate_worker(engine, a, hours, "planned", 1.0)
        per_arch[a.id] = r.hourly
    arch_meta = [{"id": a.id, "label": a.label, "task": a.task, "clothing": a.clothing, "acclimatized": a.acclimatized,
                  "source_status": a.source_status} for a in archetypes]
    pack = {
        "pack_version": 1, "heatbank_version": __version__,
        "generated_at": (now - datetime.timedelta(minutes=forecast_age_min)).isoformat(timespec="seconds"),
        "max_age_min": config.MAX_FORECAST_AGE_MIN, "degraded_work_cap_min": config.DEGRADED_WORK_CAP_MIN, "stale_min_level": config.EXPORT_STALE_MIN_LEVEL,
        "stale_raise": config.EXPORT_STALE_RAISE, "adherence_grace_min": config.ADHERENCE_GRACE_MIN,
        "provenance": {"weather_source": provider, "strain_model": model_label, "synthetic": synthetic, "disclaimer": DISCLAIMER,
                       "weather_date": sh[0].time_iso[:10] if sh else None,
                       # v0.6: the WEATHER may be real (replay of one day) while crew and clock stay simulated, so `synthetic` stays True
                       "weather_real": bool(weather_real), "attribution": attribution},
        "hours": [r["hour"] for r in next(iter(per_arch.values()))],
        "archetypes": arch_meta, "plans": per_arch,
        "escalation": {"medic_tel": _clean_tel(config.MEDIC_TEL)},
        "level_names": LEVEL_LABELS,
        "action_keys": ["normal_work", "drink_shade_break", "reduce_cool_now", "stop_cool_buddy"],
        "banner_keys": {"offline": "banner_offline", "stale": "banner_stale", "none": "banner_no_data"},
        "strings": strings.bundle(), "lang_label": strings.LANG_LABEL, "lang_status": strings.REVIEW_STATUS,
    }
    if roster:
        pack["supervisor"] = aggregate(roster, zone_names or {}, per_arch, k)
        pack["supervisor"]["zone_names"] = zone_names or {}
    return pack


def write_js(pack: dict, path: str):
    """data.js sets window.HEATBANK so the pages work from file:// with no server and no network (P5)."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("// GENERATED by heatbank.export. SIMULATED data unless provenance.synthetic is false. Do not edit.\n")
        fh.write("window.HEATBANK = " + json.dumps(pack, ensure_ascii=False, separators=(",", ":")) + ";\n")
    with open(path + ".meta.json", "w") as fh:
        json.dump(pack["provenance"] | {"generated_at": pack["generated_at"], "heatbank_version": __version__}, fh, indent=2)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Export the dashboard pack. " + DISCLAIMER)
    ap.add_argument("--scenario", choices=sorted(SCENARIOS), default="hot_humid")
    ap.add_argument("--nasa-power", nargs=3, metavar=("LAT", "LON", "YYYY-MM-DD"), help="use REAL weather of one day from NASA POWER (D8) instead of a synthetic scenario")
    ap.add_argument("--utc-offset", type=float, default=4.0, help="local time = UTC + this many hours (default 4.0, UAE)")
    ap.add_argument("--nasa-refresh", action="store_true", help="download again even if a saved copy exists")
    ap.add_argument("--toy", action="store_true", help="TOY model (not physiology). Real PHS needs pythermalcomfort.")
    ap.add_argument("--forecast-only", action="store_true", help="strip the synthetic globe temperature: exercises the radiant fallback")
    ap.add_argument("--out", default="dashboard/data.js")
    ap.add_argument("--medic-tel", default=None, help="site medic phone number for the one-tap call on the Red screen (never invented by HeatBank)")
    a = ap.parse_args(argv)
    if a.toy:
        print(f"*** {TOY_LABEL}: demo only ***", file=sys.stderr)
        eng, label = StrainEngine(toy_phs), TOY_LABEL
    else:
        eng, label = StrainEngine(), "pythermalcomfort PHS (ISO 7933)"
        try:
            problems = eng.smoke_test()
        except ImportError:
            raise SystemExit("pythermalcomfort is not installed (use --toy for a demo)")
        if problems: raise SystemExit("model smoke test failed: " + "; ".join(problems))
    import dataclasses
    config.MEDIC_TEL = a.medic_tel
    real = bool(a.nasa_power)
    if real:
        from .weather.factory import make_provider
        prov = make_provider(None, nasa_power=a.nasa_power, utc_offset_h=a.utc_offset, nasa_refresh=a.nasa_refresh)
        try: hours = prov.hours()
        except Exception as e: raise SystemExit(f"could not get the real weather: {e}")
    else:
        prov = SyntheticScenario(a.scenario); hours = prov.hours()
    if a.forecast_only: hours = [dataclasses.replace(h, tg_c=None) for h in hours]
    from .weather.nasa_power import CREDIT
    pack = build_pack(eng, hours, build_archetypes(), DEMO_ROSTER, DEMO_ZONES, label, prov.name, True,
                      weather_real=real, attribution=CREDIT if real else None)
    write_js(pack, a.out)
    print(f"wrote {a.out} ({os.path.getsize(a.out)//1024} KB), weather {prov.name}{' (REAL)' if real else ' (synthetic)'}, model {label}")


if __name__ == "__main__":
    main()
