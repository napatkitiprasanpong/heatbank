"""C7 site-node bias correction and the V5 test (plan s.6 C7, s.8 V5). OPTIONAL: first item in the cut order.

The node measures the ENVIRONMENT only (air temp, humidity, black-globe temp, battery). Never people (P3).

Audit A7: the plan says the node 'corrects forecast bias', but principle P2 says uncertainty may only raise alerts. A correction
that makes the site look COOLER than the forecast would lower alerts on the strength of one cheap sensor. So by default only
corrections that make the estimate hotter are applied; cooling corrections are reported but ignored
(config.SITE_BIAS_ALLOW_COOLING = False). Frozen or spiking sensor data is never learned from (fallback.frozen / spiked).

Node CSV columns: time_iso,tdb_c,rh_pct,tg_c,battery_pct  (hourly means; time_iso matches the forecast hour, e.g. 2026-11-18T11:00).
Data generated by the team (D3). Any node file used in a submission must be declared in DATA_SOURCES.md."""
import csv, dataclasses, statistics
from dataclasses import dataclass
from typing import Dict, List, Optional
from .. import config
from ..fallback import fallback
from ..weather.types import WeatherHour


@dataclass
class NodeObs:
    time_iso: str
    tdb_c: float
    rh_pct: Optional[float] = None
    tg_c: Optional[float] = None
    battery_pct: Optional[float] = None


@dataclass
class BiasResult:
    raw_bias_c: Optional[float]       # median(node - forecast), uncorrected for policy
    applied_bias_c: float             # what apply_bias() will add (0 if not enough data, faulty sensor, or cooling blocked)
    n_pairs: int
    reason: str


def load_node_csv(path: str) -> List[NodeObs]:
    out = []
    with open(path, newline="") as fh:
        for r in csv.DictReader(fh):
            f = lambda k: float(r[k]) if r.get(k) not in (None, "") else None
            out.append(NodeObs(r["time_iso"], f("tdb_c"), f("rh_pct"), f("tg_c"), f("battery_pct")))
    return out


def estimate_bias(forecast: List[WeatherHour], node: List[NodeObs]) -> BiasResult:
    fc: Dict[str, WeatherHour] = {h.time_iso: h for h in forecast}
    pairs = [(fc[o.time_iso].tdb_c, o.tdb_c) for o in node if o.time_iso in fc and o.tdb_c is not None]
    readings = [b for _, b in pairs]
    if len(pairs) < config.SITE_BIAS_MIN_SAMPLES:
        return BiasResult(None, 0.0, len(pairs), f"only {len(pairs)} paired hours, need {config.SITE_BIAS_MIN_SAMPLES}")
    if fallback.frozen(readings) or fallback.spiked(readings):
        return BiasResult(None, 0.0, len(pairs), "node readings look frozen or spiking: not learning from them")
    raw = statistics.median(b - a for a, b in pairs)
    clipped = max(-config.SITE_BIAS_MAX_C, min(config.SITE_BIAS_MAX_C, raw))
    if clipped < 0 and not config.SITE_BIAS_ALLOW_COOLING:
        return BiasResult(raw, 0.0, len(pairs), "site looks cooler than forecast; correction ignored (P2)")
    return BiasResult(raw, clipped, len(pairs), "ok")


def apply_bias(hours: List[WeatherHour], bias_c: float) -> List[WeatherHour]:
    """Shift air temperature (and globe temperature if present) by the applied bias. Never extrapolates humidity."""
    return [dataclasses.replace(h, tdb_c=round(h.tdb_c + bias_c, 2),
                                tg_c=None if h.tg_c is None else round(h.tg_c + bias_c, 2)) for h in hours]


def v5_bias_test(forecast: List[WeatherHour], node: List[NodeObs]) -> dict:
    """V5: learn on the first half of the paired hours, measure forecast error on the second half with and without the
    correction. Report MAE both ways. Needs REAL node data to mean anything; with synthetic node data it only proves plumbing."""
    fc = {h.time_iso: h for h in forecast}
    paired = [o for o in node if o.time_iso in fc and o.tdb_c is not None]
    paired.sort(key=lambda o: o.time_iso)
    if len(paired) < 2 * config.SITE_BIAS_MIN_SAMPLES:
        return {"status": "NOT ENOUGH DATA", "n_pairs": len(paired), "need": 2 * config.SITE_BIAS_MIN_SAMPLES}
    half = len(paired) // 2
    res = estimate_bias(forecast, paired[:half])
    test = paired[half:]
    mae_raw = statistics.mean(abs(o.tdb_c - fc[o.time_iso].tdb_c) for o in test)
    mae_cor = statistics.mean(abs(o.tdb_c - (fc[o.time_iso].tdb_c + res.applied_bias_c)) for o in test)
    return {"status": "OK", "n_train": half, "n_test": len(test), "raw_bias_c": res.raw_bias_c, "applied_bias_c": res.applied_bias_c,
            "mae_forecast_c": round(mae_raw, 2), "mae_corrected_c": round(mae_cor, 2), "reduces_error": mae_cor < mae_raw,
            "note": res.reason}
