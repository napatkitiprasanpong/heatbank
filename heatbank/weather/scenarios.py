"""D4: team-generated synthetic scenarios (hot-humid, hot-dry, cool control). Label as synthetic everywhere.
The shapes are simple diurnal curves chosen by us; they are NOT measurements of any place."""
import math
from typing import List
from .types import WeatherHour
from .. import config

SCENARIOS = {
    # tmin, tmax, rh at hottest hour, rh at coolest hour, wind m/s, peak solar W/m2
    "hot_humid": dict(tmin=27.0, tmax=35.0, rh_hot=60.0, rh_cool=85.0, wind=1.0, solar_peak=850.0),
    "hot_dry":   dict(tmin=28.0, tmax=44.0, rh_hot=15.0, rh_cool=35.0, wind=2.0, solar_peak=950.0),
    "cool":      dict(tmin=12.0, tmax=22.0, rh_hot=50.0, rh_cool=75.0, wind=1.5, solar_peak=600.0),
}


class SyntheticScenario:
    licence_note = "Generated by the team (D4). Synthetic. No external data."

    def __init__(self, scenario: str, date: str = "2026-01-01"):
        if scenario not in SCENARIOS:
            raise ValueError(f"unknown scenario {scenario!r}; choose from {sorted(SCENARIOS)}")
        self.scenario = scenario
        self.date = date
        self.name = f"synthetic:{scenario}"

    def hours(self) -> List[WeatherHour]:
        p = SCENARIOS[self.scenario]
        out = []
        for h in range(24):
            # temperature peaks at 15:00, minimum near 03:00
            x = 0.5 * (1 + math.cos(2 * math.pi * (h - 15) / 24))   # 1 at 15:00, 0 at 03:00
            tdb = p["tmin"] + (p["tmax"] - p["tmin"]) * x
            rh = p["rh_cool"] + (p["rh_hot"] - p["rh_cool"]) * x
            # solar: half-sine between 06:00 and 18:00
            solar = p["solar_peak"] * math.sin(math.pi * (h - 6) / 12) if 6 <= h <= 18 else 0.0
            tg = tdb + config.SYNTH_GLOBE_RISE_AT_1000WM2_C * solar / 1000.0
            out.append(WeatherHour(
                time_iso=f"{self.date}T{h:02d}:00", tdb_c=round(tdb, 2), rh_pct=round(rh, 1),
                wind_ms=p["wind"], solar_wm2=round(solar, 1), pressure_hpa=1010.0,
                tg_c=round(tg, 2), synthetic=True))
        return out
